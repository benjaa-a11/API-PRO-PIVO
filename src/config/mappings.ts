export function findLeagueMapping(identifier: string): LeagueMapping | undefined {
  const lower = identifier.trim().toLowerCase();
  return LEAGUE_MAPPINGS.find(
    (m) =>
      m.canonicalSlug === lower ||
      m.promiedosId?.toLowerCase() === lower ||
      m.promiedosSlug?.toLowerCase() === lower ||
      m.espnSlug?.toLowerCase() === lower ||
      m.espnId === lower,
  );
}
